let currentLang = 'en';
const slides = [...document.querySelectorAll('.hero-slide')];
const dotsWrap = document.getElementById('heroDots');
let currentSlide = 0;
let sliderTimer;

function getNested(obj, path){return path.split('.').reduce((acc, key)=> acc && acc[key], obj);}

function setLanguage(lang){
  currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.body.classList.toggle('is-ar', lang === 'ar');
  document.getElementById('langToggle').textContent = lang === 'ar' ? 'English' : 'عربي';

  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.dataset.i18n;
    if(lang === 'ar'){
      const value = getNested(translations.ar, key);
      if(value) el.textContent = value;
    }else{
      const original = el.dataset.original;
      if(original) el.textContent = original;
    }
  });

  document.querySelectorAll('[data-placeholder-en]').forEach(el=>{
    el.placeholder = lang === 'ar' ? el.dataset.placeholderAr : el.dataset.placeholderEn;
  });
}

function initI18n(){
  document.querySelectorAll('[data-i18n]').forEach(el=>{el.dataset.original = el.textContent;});
  document.getElementById('langToggle').addEventListener('click',()=>setLanguage(currentLang === 'en' ? 'ar' : 'en'));
}

function buildDots(){
  slides.forEach((_,i)=>{
    const b=document.createElement('button');
    b.className='hero-dot'+(i===0?' active':'');
    b.type='button';
    b.setAttribute('aria-label',`Go to slide ${i+1}`);
    b.addEventListener('click',()=>showSlide(i,true));
    dotsWrap.appendChild(b);
  });
}


function placeHeroControls(){
  const controls = document.querySelector('.hero-controls');
  const active = slides[currentSlide];
  if(!controls || !active) return;
  const actions = active.querySelector('.hero-actions');
  if(actions && controls.parentElement !== active.querySelector('.hero-copy')){
    actions.before(controls);
  }
}

function showSlide(index, manual=false){
  currentSlide=(index+slides.length)%slides.length;
  slides.forEach((s,i)=>s.classList.toggle('active',i===currentSlide));
  document.querySelectorAll('.hero-dot').forEach((d,i)=>d.classList.toggle('active',i===currentSlide));
  placeHeroControls();
  slides[currentSlide].querySelectorAll('.reveal').forEach(el=>{el.classList.remove('in');setTimeout(()=>el.classList.add('in'),40)});
  if(manual) restartSlider();
}
function nextSlide(){showSlide(currentSlide+1)}
function prevSlide(){showSlide(currentSlide-1,true)}
function restartSlider(){clearInterval(sliderTimer);sliderTimer=setInterval(nextSlide,6500)}
function initSlider(){buildDots();placeHeroControls();document.getElementById('nextSlide').addEventListener('click',()=>showSlide(currentSlide+1,true));document.getElementById('prevSlide').addEventListener('click',prevSlide);restartSlider();}

function initReveal(){
  const observer=new IntersectionObserver((entries)=>{
    entries.forEach(entry=>{if(entry.isIntersecting){entry.target.classList.add('in');observer.unobserve(entry.target);}})
  },{threshold:.12});
  document.querySelectorAll('.reveal').forEach(el=>observer.observe(el));
}

function initNav(){
  const header=document.getElementById('siteHeader');
  window.addEventListener('scroll',()=>header.classList.toggle('scrolled',window.scrollY>24));
  const toggle=document.getElementById('menuToggle');
  const nav=document.getElementById('mainNav');
  toggle.addEventListener('click',()=>{
    const open=nav.classList.toggle('open');
    toggle.setAttribute('aria-expanded',String(open));
  });
  nav.querySelectorAll('a').forEach(a=>a.addEventListener('click',()=>{nav.classList.remove('open');toggle.setAttribute('aria-expanded','false')}));
}

function initForm(){
  const form=document.getElementById('contactForm');
  form.addEventListener('submit',(e)=>{
    e.preventDefault();
    const name=document.getElementById('name').value.trim();
    const company=document.getElementById('company').value.trim();
    const email=document.getElementById('email').value.trim();
    const phone=document.getElementById('phone').value.trim();
    const interest=document.getElementById('interest').value;
    const message=document.getElementById('message').value.trim();
    const subject=encodeURIComponent('Scalixr TrueScale Inquiry from '+(name||'Website Visitor'));
    const body=encodeURIComponent(`Name: ${name}\nCompany: ${company}\nEmail: ${email}\nPhone: ${phone}\nInterest: ${interest}\n\nMessage:\n${message}`);
    window.location.href=`mailto:info@scalixrai.com?subject=${subject}&body=${body}`;
  });
}

window.addEventListener('load',()=>{
  initI18n();
  initSlider();
  initReveal();
  initNav();
  initForm();
  document.getElementById('year').textContent = new Date().getFullYear();
  setTimeout(()=>document.getElementById('siteLoader').classList.add('hide'),700);
});
